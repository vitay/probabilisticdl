"""Sampling a flow matching model with a few Euler steps (flow matching chapter).

Samples of the 2D mixture of `score.py` generated by integrating the exact marginal velocity of `flow-matching-paths.py`
with K Euler steps, from the same noise samples. With K = 1, all samples land on the mean of the data, as the velocity
at t = 0 is E[x_1] - x_0; the samples spread into the two modes as K increases.
Figures: final samples for a few values of K (`flow-matching-sampling.png`), and an animation over K
(`flow-matching-sampling.gif`).

Run from anywhere: `python src/img/flow-matching-sampling.py` writes `flow-matching-sampling.png` and
`flow-matching-sampling.gif` next to this file.
"""

import importlib
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.animation import FuncAnimation, PillowWriter

sys.path.insert(0, str(Path(__file__).parent))
paths = importlib.import_module("flow-matching-paths")

N = 1000
STEPS = [1, 2, 5, 50]
ANIMATION_STEPS = [1, 2, 3, 4, 5, 6, 8, 10, 13, 16, 20, 25, 30, 40, 50]

x0 = np.random.default_rng(0).normal(size=(N, 2))
samples = {k: paths.integrate(x0, k)[1][-1] for k in sorted(set(STEPS + ANIMATION_STEPS))}

# Palette: categorical slots 1-2 of the dataviz reference palette, plus text/grid tokens
DENSITY, SAMPLE = "#2a78d6", "#eb6834"
TEXT, MUTED, GRID = "#0b0b0b", "#52514e", "#e4e3df"

plt.rcParams.update({
    "font.size": 11,
    "text.color": TEXT,
    "axes.labelcolor": MUTED,
    "xtick.color": MUTED,
    "ytick.color": MUTED,
    "axes.edgecolor": GRID,
})

g = np.linspace(-5, 5, 250)
G1, G2 = np.meshgrid(g, g)
log_density = np.log(paths.density(np.stack([G1, G2], axis=-1), 0.999))


def draw(ax, k):
    ax.contour(G1, G2, log_density, levels=8, colors=DENSITY, linewidths=1, linestyles="solid", alpha=0.4)
    ax.scatter(samples[k][:, 0], samples[k][:, 1], color=SAMPLE, s=4, alpha=0.6)
    ax.set_xlim(-5, 5)
    ax.set_ylim(-5, 5)
    ax.set_aspect("equal")
    ax.set_xlabel("$x_1$")
    ax.set_title(f"{k} Euler step" + ("s" if k > 1 else ""), color=TEXT, fontsize=11)
    ax.grid(color=GRID, lw=0.8)
    ax.set_axisbelow(True)
    for side in ["top", "right"]:
        ax.spines[side].set_visible(False)


# Static figure
fig, axes = plt.subplots(1, len(STEPS), figsize=(15, 4.1), sharey=True)
for ax, k in zip(axes, STEPS):
    draw(ax, k)
axes[0].set_ylabel("$x_2$")
fig.tight_layout()
fig.savefig(Path(__file__).with_suffix(".png"), dpi=200, bbox_inches="tight", facecolor="white")

# Animation over the number of steps
fig, ax = plt.subplots(figsize=(4.8, 4.8))
fig.subplots_adjust(left=0.15)


def update(i):
    ax.clear()
    draw(ax, ANIMATION_STEPS[i])
    ax.set_ylabel("$x_2$")


frames = list(range(len(ANIMATION_STEPS))) + [len(ANIMATION_STEPS) - 1] * 4
animation = FuncAnimation(fig, update, frames=frames)
animation.save(Path(__file__).with_suffix(".gif"), writer=PillowWriter(fps=2), dpi=90,
               savefig_kwargs={"facecolor": "white"})
